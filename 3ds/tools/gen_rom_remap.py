#!/usr/bin/env python3
"""M01: write 3ds/src/rom_remap.h from ver/us/splat.yaml.
Dropped ROM ranges: world map overlays mac_01..gv_01 (map code is linked into the 3dsx),
dead maps, junk gap unk_1C84D30, copy_* segments. Kept ranges become {rom_start,len,packed_off}."""
import re, sys, os
ROM = 0x2800000
import yaml
# PyYAML parse: the old line scanner missed 121 segments written as "- type: code / start: / name:".
Y = yaml.load(open('ver/us/splat.yaml'), Loader=yaml.CSafeLoader)
segs = []  # (start, name)
code_keys = set()  # (start, name) of splat type code segments (RR1)
for s in Y['segments']:
    if isinstance(s, list):
        segs.append([s[0], str(s[2] if len(s) > 2 else s[1] if len(s) > 1 else '?')])
        if len(s) > 1 and s[1] == 'code': code_keys.add((s[0], segs[-1][1]))
    else:
        segs.append([s['start'], s.get('name') or s.get('dir', '?')])
        if s.get('type') == 'code': code_keys.add((s['start'], segs[-1][1]))
segs = [s for s in segs if s[0] is not None]
segs.sort()
def end_of(i):  # next segment with a larger start (heaps and others have length 0 and share a start)
    return next((x[0] for x in segs[i + 1:] if x[0] > segs[i][0]), ROM)
names = [s[1] for s in segs]
drops = []
# M02: the block 0x315B80..0x800880 mixes code overlays with data. Drop only the overlays (battle, partner, effect, map
# and engine code linked into the 3dsx, their ROM ranges are empty or NULL in ld_addrs.h). Keep sprite_shading_profiles
# (read through defsym) and effect_gfx_* (graphics data that the port does not load yet, but a fix will need).
BLOCK = (0x3169F0, 0x800880)
# M02: resident game code that the 3dsx links as ARM. splat type code, all subsegments c. The ROM_START symbols are
# empty ((u8*)1, or a defsym alias of gPartnerStatus), so DMA_COPY_SEGMENT copies 0 bytes. main is NOT here: the trace
# reads 8,544 B inside it.
CODE_OVERLAYS = {'engine1', 'engine2', 'evt', 'engine4', 'entity', 'pause', 'filemenu', 'battle_code'}
def isdrop(n, s):
    if n in CODE_OVERLAYS and s < 0x1CC310: return True
    # S19b: the Lava Piranha animation scripts (world_model_anim_kzn_*) are data that dma_copy reads by ROM offset.
    if BLOCK[0] <= s < BLOCK[1]: return not (n.startswith('effect_gfx_') or n.startswith('world_model_anim_kzn_'))
    return n.startswith('dead_') or n.startswith('copy_') or n == 'unk_1C84D30' or (0x800880 <= s < 0xE20110)
for i, (s, n) in enumerate(segs):
    if s >= 0x2800000: continue
    if isdrop(n, s): drops.append([max(s, 0xEA0900) if n == 'dead_kzn_11_end' else s, end_of(i), n])  # BombableRock model ends at 0xEA0900
# the world overlay run ends at the heaps2 data start (0xE20110). Merge touching ranges.
merged = []
drops.sort()
for d in drops:
    if merged and d[0] <= merged[-1][1]:
        merged[-1][1] = max(merged[-1][1], d[1]); merged[-1][2] += '+' + d[2] if len(merged[-1][2]) < 60 else ''
    else: merged.append(d)
for m in merged:
    m[2] = m[2].split('+')[0] + ('+' if '+' in m[2] else '')
# RR1: the code segments are linked as ARM into the 3dsx. Their ROM bytes stay only where the full-ROM trace reads them
# (3ds/rom_code_keep.txt, written from build3ds/romtrace_full.txt). Every other byte of a code segment is dropped.
KEEP = [tuple(int(x, 16) for x in l.split()[:2]) for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rom_code_keep.txt')) if l.strip() and not l.startswith('#')]
for i, (s, n) in enumerate(segs):
    if s >= ROM or (s, n) not in code_keys: continue
    e = end_of(i)
    if e <= s: continue
    cur = s
    for ks, ke in sorted(k for k in KEEP if k[0] < e and k[1] > s):
        if ks > cur: merged.append([cur, min(ks, e), n + '(code)'])
        cur = max(cur, min(ke, e))
    if cur < e: merged.append([cur, e, n + '(code)'])
merged.sort()
merged2 = []
for d in merged:
    if merged2 and d[0] <= merged2[-1][1]: merged2[-1][1] = max(merged2[-1][1], d[1]); merged2[-1][2] = merged2[-1][2]
    else: merged2.append(d)
merged = merged2
kept = []; pos = 0; packed = 0
for s, e, n in merged:
    if s > pos: kept.append((pos, s - pos, packed)); packed += s - pos
    pos = e
if pos < ROM: kept.append((pos, ROM - pos, packed)); packed += ROM - pos
out = ['/* Generated by 3ds/tools/gen_rom_remap.py from ver/us/splat.yaml. Do not edit. */',
       '#define PM_ROM_FULL 0x%08Xu' % ROM, '#define PM_ROM_PACKED 0x%08Xu' % packed,
       'typedef struct { unsigned start, len, packed_off; } PmRomSeg;',
       'static const PmRomSeg pm_rom_keep[] = {']
out += ['    { 0x%08X, 0x%08X, 0x%08X },' % k for k in kept] + ['};',
       'typedef struct { unsigned start, end; const char* name; } PmRomDrop;', 'static const PmRomDrop pm_rom_drop[] = {']
out += ['    { 0x%08X, 0x%08X, "%s" },' % (s, e, n) for s, e, n in merged] + ['};']
# S19b: ranges of s16 data. The ROM is big-endian. nuPiReadRom swaps each s16 of a read that lies in one of these.
sw = [(s, end_of(i)) for i, (s, n) in enumerate(segs) if n.startswith('world_model_anim_kzn_')]
lo, hi = min(s for s, e in sw), max(e for s, e in sw)
assert sum(e - s for s, e in sw) == hi - lo  # contiguous
out += ['typedef struct { unsigned start, end; } PmRomSwap16;', 'static const PmRomSwap16 pm_rom_swap16[] = {',
        '    { 0x%08X, 0x%08X },' % (lo, hi), '};']
open('3ds/src/rom_remap.h', 'w').write('\n'.join(out) + '\n')
tot = sum(e - s for s, e, n in merged)
for s, e, n in merged: print('drop %08X..%08X %8d %s' % (s, e, e - s, n))
print('dropped', tot, 'packed', packed)
