"""S7CONV: the symbol scan of the gfx table tool (gen_gfx_tab.sh, row S7CONV design note 2).
Usage: gen_gfx_syms.py <out gconv_in.c> <gfx source .c> ...
Writes one C file that includes every input source (so sizeof works) and the symbol map gconv_sym[]: every non-static
`Gfx NAME[] =` and `Vtx NAME[..] =` of the sources and their `#include "*.inc.c"` files (under assets/us), and every
INCLUDE_IMG/PAL/RAW NAME (its end from the NAME_gend label of 3ds/tools/gconv_inc/include_asset.h). Run from the repo root."""
import re
import sys
import pathlib

DEF = re.compile(r"^(Gfx|Vtx)\s+(\w+)\s*\[[^\]]*\]\s*=", re.M)
MTX = re.compile(r"^Mtx\s+(\w+)\s*(\[[^\]]*\])?\s*=", re.M)
INC = re.compile(r'^\s*#include\s+"([^"]+\.inc\.c)"', re.M)
IMG = re.compile(r"INCLUDE_(?:IMG|PAL|RAW)\(\s*\"[^\"]*\"\s*,\s*(\w+)\s*\)")


def scan(path, out):
    text = path.read_text(encoding="utf-8", errors="replace")
    for kind, name in DEF.findall(text):
        out.append((kind, name))
    for m in MTX.finditer(text):
        out.append(("Mtx", m.group(1)))
    for name in IMG.findall(text):
        out.append(("Img", name))
    for inc in INC.findall(text):
        p = pathlib.Path("assets/us") / inc
        if not p.exists():
            p = path.parent / inc
        if not p.exists():
            sys.exit(f"gen_gfx_syms: include {inc} of {path} not found")
        scan(p, out)


def main():
    out_c, srcs = sys.argv[1], list(dict.fromkeys(sys.argv[2:]))
    syms = []
    for s in srcs:
        scan(pathlib.Path(s), syms)
    seen, uniq = set(), []
    for k, n in syms:
        if n not in seen:
            seen.add(n)
            uniq.append((k, n))
    lines = ["/* Generated by 3ds/tools/gen_gfx_syms.py (S7CONV): the inputs of the gfx table tool and their symbol map. */"]
    lines += [f'#include "{s}"' for s in srcs]
    lines += ['#include "nd_gconv.h"']
    for k, n in uniq:
        if k == "Img":
            lines.append(f"extern unsigned char {n}_gend[];")
    lines.append("const GSym gconv_sym[] = {")
    for k, n in uniq:
        if k == "Img":
            lines.append(f'    {{ "{n}", GS_IMG, (const void*){n}, (const void*){n}_gend }},')
        else:
            gk = {"Gfx": "GS_GFX", "Vtx": "GS_VTX", "Mtx": "GS_MTX"}[k]
            lines.append(f'    {{ "{n}", {gk}, (const void*){n}, (const void*)((const char*){n} + sizeof {n}) }},')
    lines.append("};")
    lines.append(f"const unsigned gconv_nsym = {len(uniq)}u;")
    pathlib.Path(out_c).write_text("\n".join(lines) + "\n")
    print(f"gen_gfx_syms: {len(srcs)} sources {len(uniq)} symbols", file=sys.stderr)


main()
