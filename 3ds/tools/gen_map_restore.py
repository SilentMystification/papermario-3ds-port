#!/usr/bin/env python3
"""MS01: restore the static data of a map when the map is loaded again (the N64 overlay DMA did that).
  gen_map_restore.py learn <link map> <probe log>...   add the data symbols that changed in the probe logs to 3ds/map_restore.txt
  gen_map_restore.py                                    write 3ds/ld/map_restore.ld (included by 3ds/ld/3dsx.ld) and 3ds/src/map_restore_table.c
map_restore.txt: lines "<owner> <object path from area_..> <input section>" = .data symbols that change at run time
(found with the dataprobe debug switch). Their input sections are grouped by the linker script into one block per map
(pristine copy is taken at the first entry, memcpy back at later entries). All .bss of a linked map is grouped in a second
block and zeroed at entry (the N64 data of a map starts from its initial value, an initialised zero is .bss here)."""
import os, re, sys, collections
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.normpath(os.path.join(here, '..', '..'))
sys.path.insert(0, here)
RST = os.path.join(root, '3ds', 'map_restore.txt')

def load_rst():
    return [l.split() for l in open(RST) if l.strip() and not l.startswith('#')] if os.path.exists(RST) else []

if len(sys.argv) > 1 and sys.argv[1] == 'learn':
    import map_data_sizes as M
    secs = [r for r in M.sections(sys.argv[2]) if r['kind'] == 'd' and r['owner']]
    have = set(map(tuple, load_rst()))
    for lg in sys.argv[3:]:
        for l in open(lg, errors='replace'):
            m = re.search(r'dprobe: (?:leave|entry) (\S+) d (\S+) size', l)
            if not m: continue
            mid, sym = m.groups()
            for r in secs:
                own = r['owner']
                if r['sym'] == sym and (own == mid or (own == '@machi' and mid.startswith('mac_')) or (own == '@dgb' and mid.startswith('dgb_'))):
                    have.add((own, r['file'][r['file'].index('area_'):], r['sec']))
    with open(RST, 'w', newline='\n') as f:
        f.write('# MS01: .data symbols of a map that change at run time (gen_map_restore.py learn). owner, object file, input section\n')
        for t in sorted(have): f.write(' '.join(t) + '\n')
    print(len(have), 'rows in', RST)
    sys.exit(0)

files = collections.defaultdict(list)  # owner -> object path from area_ (for .bss)
for l in open(os.path.join(root, '3ds', 'maps.cmake')):
    m = re.search(r'/src/world/(area_\w+)/(?:(\w+)/)?([\w.]+)\.c$', l)
    if not m: continue
    area, d, fn = m.groups()
    own = ('@machi' if d == 'machi' else d) if d else '@' + area[5:]
    files[own].append('%s/%s%s.o' % (area, d + '/' if d else '', fn))
rst = collections.defaultdict(list)
for own, obj, sec in load_rst(): rst[own].append((obj, sec))
owners = sorted(set(files) | set(rst))
nm = lambda o: o.lstrip('@')
ld = ['/* Generated by tools/gen_map_restore.py (slice MS01). One block per map: changing .data symbols (d), all .bss (b). */',
      '  .mapstat : ALIGN(4)', '  {', '    LONG(0);']
for o in owners:
    ld += ['    . = ALIGN(4); __ms_%s_d0 = .;' % nm(o)]
    ld += ['    *%s(%s)' % (obj, sec) for obj, sec in sorted(rst[o])]
    ld += ['    . = ALIGN(4); __ms_%s_d1 = .; __ms_%s_b0 = .;' % (nm(o), nm(o))]
    ld += ['    *%s(.bss .bss.* COMMON)' % f for f in sorted(files[o])]
    ld += ['    . = ALIGN(4); __ms_%s_b1 = .;' % nm(o)]
ld += ['  } : data']
open(os.path.join(root, '3ds', 'ld', 'map_restore.ld'), 'w', newline='\n').write('\n'.join(ld) + '\n')
c = ['/* Generated by tools/gen_map_restore.py (slice MS01). Block addresses come from ld/map_restore.ld. */', '#include "pm_port.h"']
c += ['extern unsigned char __ms_%s_d0[], __ms_%s_d1[], __ms_%s_b0[], __ms_%s_b1[];' % ((nm(o),) * 4) for o in owners]
c += ['PmMapRst pm_map_rst[] = {']
c += ['    { "%s", __ms_%s_d0, __ms_%s_d1, __ms_%s_b0, __ms_%s_b1, 0 },' % ((o, nm(o), nm(o), nm(o), nm(o))) for o in owners]
c += ['};', 'const int pm_map_rst_n = %d;' % len(owners)]
open(os.path.join(root, '3ds', 'src', 'map_restore_table.c'), 'w', newline='\n').write('\n'.join(c) + '\n')
print('owners', len(owners), 'with .data rows', len(rst), 'rows', sum(map(len, rst.values())), 'bss files', sum(map(len, files.values())))
