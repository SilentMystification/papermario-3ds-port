"""Slice S30. Generate 3ds/maps.cmake and 3ds/map_syms.lds from the real decomp.
- Sources: every .c of src/world/area_<area>/<map>/ that the decomp build.ninja compiles (the N64 build list).
- The real src/world/world.c (with its full gAreas table) is built whole. Its MAP() rows name <map>_settings,
  <map>_map_init and <map>_ROM_START/_END/_VRAM. This tool writes:
    * stub_include/map_rom_ranges.h: <map>_ROM_START/_END/_VRAM = null for every map (the map code is linked in, so
      dmaStart is null: no overlay DMA) and for the in-place map data segments that the maps DMA at run time
    * map_syms.lds: <map>_settings = pm_unlinked_map (and <map>_map_init) for every map that is NOT linked: the row points
      at the one sentinel byte in pm_map.c, and the GotoMap guard refuses it. (A plain 0 does not work: 3dsxtool
      rejects an absolute relocation, "Relocation to invalid address".)
Usage: python gen_map_sources.py [--skip map[,map...]] [--areas a,b,c]
  --areas: only link maps of these areas (default all). --skip: leave these maps unlinked (reason in HANDOFF / maps_skip.txt).
maps_skip.txt is read too: one map per line, or "area:<name>" for a whole area, '#' comments."""
import re, sys, os, collections
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
sep = chr(92)
pat = re.compile(r"build ver" + re.escape(sep) + "us" + re.escape(sep) + "build" + re.escape(sep) +
                 r"(src" + re.escape(sep) + r"world" + re.escape(sep) + r"area_(\w+)" + re.escape(sep) + r"([^" + re.escape(sep) + r" ]+)" +
                 re.escape(sep) + r"[^ ]+\.c)\.o: cc")
src = collections.OrderedDict()   # (area, map) -> [files]
extra = []  # entity and script_api files of the real build (the maps use them: Entity_* blueprints, push blocks)
area_files = collections.OrderedDict()  # area -> files that sit directly in src/world/area_<area>/ (data segments of the area)
pat2 = re.compile(r"build ver" + re.escape(sep) + "us" + re.escape(sep) + "build" + re.escape(sep) +
                  r"(src" + re.escape(sep) + r"world" + re.escape(sep) + r"area_(\w+)" + re.escape(sep) + r"[^" + re.escape(sep) + r" ]+\.c)\.o: cc")
pat3 = re.compile(r"build ver" + re.escape(sep) + "us" + re.escape(sep) + "build" + re.escape(sep) +
                  r"(src" + re.escape(sep) + r"(?:entity|world" + re.escape(sep) + r"script_api)" + re.escape(sep) + r"[^ ]+\.c)\.o: cc")
for l in open(os.path.join(root, "build.ninja"), encoding="utf8"):
    m3 = pat3.match(l)
    if m3:
        extra.append(m3.group(1).replace(sep, "/"))
    m2 = pat2.match(l)
    if m2:
        area_files.setdefault(m2.group(2), []).append(m2.group(1).replace(sep, "/"))
    m = pat.match(l)
    if m:
        src.setdefault((m.group(2), m.group(3)), []).append(m.group(1).replace(sep, "/"))
# map table of the real world.c: area -> [(map, with_init)]
w = re.sub(r"//[^\n]*", "", open(os.path.join(root, "src/world/world.c"), encoding="utf8", errors="replace").read())
table = collections.OrderedDict()
for m in re.finditer(r"MapConfig\s+(\w+)_maps\[\]\s*=\s*\{(.*?)\n\};", w, re.S):
    table[m.group(1)] = [(r.group(2), r.group(1) == "_WITH_INIT") for r in re.finditer(r"\{\s*MAP(_WITH_INIT)?\((\w+)\)", m.group(2))]
args = sys.argv[1:]
skip, areas, skip_areas = set(), None, set()
if "--skip" in args: skip |= set(args[args.index("--skip") + 1].split(","))
if "--areas" in args: areas = args[args.index("--areas") + 1].split(",")
sk = os.path.join(root, "3ds", "maps_skip.txt")
if os.path.exists(sk):
    for l in open(sk):
        l = l.split("#")[0].strip()
        if l.startswith("area:"): skip_areas.add(l[5:].strip())
        elif l: skip.add(l)
BASE = {"hos_05", "kmr_02", "kmr_20", "osr_00", "kkj_00", "mac_00"}  # linked before S30 (sources are in CMakeLists.txt), always linked
cm = ["# Generated by tools/gen_map_sources.py (slice S30). Real sources of the linked maps (src/world/area_<area>/<map>/)."]
hdr = ["/* Generated by tools/gen_map_sources.py (slice S30). Map overlay ranges are null: map code and data are linked in. */"]
ld = ["/* Generated by tools/gen_map_sources.py (slice S30). Link-time zeros for the map table of the real world.c. */"]
linked, unlinked = [], []
for a, rows in table.items():
    files = []
    for mp, init in rows:
        ok = (mp in BASE or (areas is None and a not in skip_areas) or (areas is not None and a in areas)) and mp not in skip and (a, mp) in src
        for s in ("ROM_START", "ROM_END", "VRAM"):
            hdr.append("#define %s_%s ((u8*)0)" % (mp, s))
        if ok:
            files += src[(a, mp)]
            linked.append(mp)
        else:
            ld.append("%s_settings = pm_unlinked_map;" % mp)
            if init: ld.append("%s_map_init = pm_unlinked_map;" % mp)
            unlinked.append(mp)
    if files:
        files += area_files.get(a, [])
    cm.append("set(MAP_SRC_%s" % a)
    cm += ["    ${DECOMP}/" + p for p in files]
    cm.append(")")
cm.append("set(MAP_SRC_extra")
cm += ["    ${DECOMP}/" + p for p in extra]
cm.append(")")
cm.append("set(MAP_AREAS %s extra)" % " ".join(table))
open(os.path.join(root, "3ds", "maps.cmake"), "w", newline="\n").write("\n".join(cm) + "\n")
hdr += ["#define dgb_01_smash_bridges_%s ((u8*)0)" % s for s in ("ROM_START", "ROM_END", "VRAM")]  # smash_bridges.c is linked in place
open(os.path.join(root, "3ds", "stub_include", "map_rom_ranges.h"), "w", newline=chr(10)).write(chr(10).join(hdr) + chr(10))
open(os.path.join(root, "3ds", "map_syms.lds"), "w", newline=chr(10)).write(chr(10).join(ld) + chr(10))
print("linked", len(linked), "unlinked", len(unlinked), "files", sum(len(src[(a, m)]) for a, r in table.items() for m, _ in r if m in linked and (a, m) in src))
