"""Generate 3ds/stub_include/battle_ld_addrs.h (slice S19).
Battle code overlays (battle_code, btl_states_menus, battle_partner_*, battle_move_*, action_cmd_*, battle_area_*) are linked
in, so every ROM/VRAM range is empty: dma_copy(1, 1, 1) copies nothing. Names come from the generated ver/us/build/include/ld_addrs.h."""
import re, pathlib, yaml  # needs PyYAML (build3ds/.venv_e01/Scripts/python.exe has it)
root = pathlib.Path(__file__).resolve().parents[2]
ld = (root / "ver/us/build/include/ld_addrs.h").read_text()
names = sorted(set(re.findall(r"extern Addr (\w+)_ROM_START;", ld)))
pat = re.compile(r"^(battle_area_|action_cmd_|battle_move_|battle_partner_|battle_code$|btl_states_menus$)")
# every segment of the battle vram classes (items, star powers, level_up, starpoint, ...)
segs = yaml.load((root / "ver/us/splat.yaml").read_text(encoding="utf8"), Loader=yaml.CSafeLoader)["segments"]
classes = {"battle_code", "battle_move", "action_cmd", "battle_partner"}
extra = {s["name"] for s in segs if isinstance(s, dict) and s.get("vram_class") in classes and "name" in s}
out = ["/* Generated by 3ds/tools/gen_battle_ld.py. */", "#ifndef BATTLE_LD_ADDRS_H", "#define BATTLE_LD_ADDRS_H"]
n = 0
for nm in names:
    if pat.match(nm) or nm in extra:
        out += [f"#define {nm}_ROM_START ((u8*)1)", f"#define {nm}_ROM_END ((u8*)1)", f"#define {nm}_VRAM ((u8*)1)"]
        n += 1
out.append("#endif")
(root / "3ds/stub_include/battle_ld_addrs.h").write_text("\n".join(out) + "\n")
print(n)
