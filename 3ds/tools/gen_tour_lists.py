"""CUR1: compiles the tour lists into 3ds/src/pm_tour_lists.h (pm_warp.c; the console has no SD file, so the tour reads only this header).

- pm_tour_spots: every line of 3ds/tours/spots.txt (map:entry@x:y:z, one per map, POS1), one '\\n' per line. tourlist=all takes the
  spot of each map from this table (tour_spot), else map:0.
- pm_tour_curated: the maps of 3ds/tours/curated.txt (bench.py tour-curate; one map:entry per line, # comments). Each item is the spot
  of the map from spots.txt when the file has the map, else map:0. tourlist=curated reads this list.

Run: python 3ds/tools/gen_tour_lists.py. Do not edit the output.
"""
import os
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
tours = os.path.join(root, "3ds", "tours")
cur = os.path.join(tours, "curated.txt")
spots_file = os.path.join(tours, "spots.txt")
out = os.path.join(root, "3ds", "src", "pm_tour_lists.h")


def tokens(path):
    """The first token of each data line of path (comments and blank lines skipped), in file order."""
    res = []
    for line in open(path, encoding="utf-8"):
        s = line.split("#", 1)[0].strip()
        if s:
            res.append(s.split()[0])
    return res


spot_tokens = []  # one line per map (an exact repeat of a line is dropped; two spots for one map is an error)
spot = {}
for t in tokens(spots_file):
    m = t.split(":", 1)[0]
    if m in spot:
        if spot[m] != t:
            sys.exit("gen_tour_lists: map %s has two spots in spots.txt (%s, %s)" % (m, spot[m], t))
        continue
    spot[m] = t
    spot_tokens.append(t)
if not spot_tokens:
    sys.exit("gen_tour_lists: no spots in spots.txt")

items, seen, source = [], set(), []
for line in open(cur, encoding="utf-8"):
    if line.startswith("# source:"):
        source.append(line.strip())
    s = line.split("#", 1)[0].strip()
    if not s:
        continue
    m = s.split(":", 1)[0]
    if m in seen:
        sys.exit("gen_tour_lists: map %s twice in curated.txt" % m)
    seen.add(m)
    items.append(spot.get(m, m + ":0"))
if not items:
    sys.exit("gen_tour_lists: no maps in curated.txt")


def c_lines(name, values):
    """A C string of the values, one per line ('\\n' ends each), split over source lines."""
    return ['static const char %s[] =' % name] + ['    "%s\\n"' % v for v in values] + ['    ;']


hdr = ["/* generated by tools/gen_tour_lists.py from 3ds/tours/spots.txt and 3ds/tours/curated.txt. Do not edit. */"]
hdr += ["/* %s */" % s[2:] for s in source]
hdr += ["#define PM_TOUR_SPOTS_N %d" % len(spot_tokens), "#define PM_TOUR_CURATED_N %d" % len(items)]
body = hdr + c_lines("pm_tour_spots", spot_tokens)
body += ["static const char pm_tour_curated[] = \"%s\";" % ",".join(items)]
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(body) + "\n")
print("%s: %d spots, %d curated maps" % (os.path.relpath(out, root), len(spot_tokens), len(items)))
