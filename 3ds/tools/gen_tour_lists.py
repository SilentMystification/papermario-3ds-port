"""CUR1: compiles 3ds/tours/curated.txt (bench.py tour-curate) into 3ds/src/pm_tour_lists.h for tourlist=curated (pm_warp.c).

Item per map of curated.txt (one per line, map:entry, # comments): the first token of the map's line in 3ds/tours/spots.txt
when that file has the map (map:entry@x:y:z), else map:0 (entry 0). Run: python 3ds/tools/gen_tour_lists.py. Do not edit the output.
"""
import os
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
tours = os.path.join(root, "3ds", "tours")
cur = os.path.join(tours, "curated.txt")
spots_file = os.path.join(tours, "spots.txt")
out = os.path.join(root, "3ds", "src", "pm_tour_lists.h")

spots = {}
if os.path.exists(spots_file):
    for line in open(spots_file, encoding="utf-8"):
        s = line.split("#", 1)[0].strip()
        if not s:
            continue
        tok = s.split()[0]
        spots.setdefault(tok.split(":", 1)[0], tok)

items, seen, source = [], set(), []
for line in open(cur, encoding="utf-8"):
    if line.startswith("# source:"):
        source.append(line.strip())
    s = line.split("#", 1)[0].strip()
    if not s:
        continue
    m = s.split(":", 1)[0]
    if m in seen:
        sys.exit("gen_tour_lists: map %s twice in curated.txt" % m)
    seen.add(m)
    items.append(spots.get(m, m + ":0"))

if not items:
    sys.exit("gen_tour_lists: no maps in curated.txt")
body = ",".join(items)
hdr = ["/* generated by tools/gen_tour_lists.py from 3ds/tours/curated.txt (and spots.txt when it has the map). Do not edit. */"]
hdr += ["/* %s */" % s[2:] for s in source]
hdr += ["#define PM_TOUR_CURATED_N %d" % len(items),
        'static const char pm_tour_curated[] = "%s";' % body]
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(hdr) + "\n")
print("%s: %d maps, spots.txt %s" % (os.path.relpath(out, root), len(items), "read" if spots else "absent"))
