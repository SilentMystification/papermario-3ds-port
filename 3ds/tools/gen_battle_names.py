"""M03: writes 3ds/stub_include/battle_name_table.h (name, value) rows from src/battle/battle_names.h and stage_names.h.
Used by the `battle=<formation>:<stage>` debug switch in pm_warp.c (class E, no game logic)."""
import re, os
root = os.path.join(os.path.dirname(__file__), '..', '..')
rows = []
for f in ('src/battle/battle_names.h', 'src/battle/stage_names.h'):
    for m in re.finditer(r'^\s*(BTL_\w+)\s*=\s*(0x[0-9A-Fa-f]+)', open(os.path.join(root, f)).read(), re.M):
        rows.append('    { "%s", %s },' % (m.group(1), m.group(2)))
out = os.path.join(root, '3ds/stub_include/battle_name_table.h')
open(out, 'w').write('/* generated by tools/gen_battle_names.py */\n' + '\n'.join(rows) + '\n')
print(len(rows), 'names')
