#!/usr/bin/env python3
"""gen_nd_gbi.py: generate 3ds/include/nd_gbi_leaf.h from the active gSP and gDP macros of the game build (plan_native_slices S2-1).

  sh 3ds/tools/gen_nd_gbi.sh        (dumps the macros with gcc -E -dM in docker pm3ds-host:1, then runs this script)

A LEAF macro writes its words itself (its body calls no other gSP or gDP macro). Every leaf gets two definitions in the output:
  ND_O_<name>   the original body (copy of the active definition)
  <name>        the bridge form: the original body writes the words into a temporary list first, nd_words() decodes them into the native
                state, then the original body writes the real packet. Each argument is evaluated twice. The first parameter (pkt) is used as often
                as the original used it, so a pkt expression with a side effect (gMainGfxPos++) advances as before.
A COMPOUND or ALIAS macro (its body calls other gSP or gDP macros: gDPSetCombineMode, gDPLoadTextureTile, gSPSetLights1 ...) is not touched. It expands
into wrapped leaves, so each word is decoded once, at the leaf.
Leaves the native state cannot decode (ucode loads, sprite 2D, lines) become #error: a file that force-includes nd_gbi.h cannot use them.
"""
import re, sys

DENY = {"gSPLoadUcode", "gSPLoadUcodeEx", "gSPLoadUcodeL", "gSPSprite2DBase", "gSPSprite2DDraw", "gSPSprite2DScaleFlip", "gSPLine3D", "gSPLineW3D"}


def parse(dump):
    macros = {}
    for ln in open(dump, errors="replace"):
        m = re.match(r"#define (g[SD]P[A-Za-z0-9_]*)\(([^)]*)\) (.*)$", ln.rstrip("\n"))
        if m:
            macros[m.group(1)] = ([p.strip() for p in m.group(2).split(",") if p.strip()], m.group(3))
    return macros


def main(dump, out, rec_out=None):
    macros = parse(dump)
    names = set(macros)
    leaf, comp = [], []
    for n in sorted(macros):
        params, body = macros[n]
        refs = {w for w in re.findall(r"\bg[SD]P[A-Za-z0-9_]*\b", body) if w in names and w != n}
        if refs:
            if "words." in body:
                print("WARNING: %s mixes direct words and inner macros: %s" % (n, sorted(refs)), file=sys.stderr)
            comp.append(n)
        else:
            leaf.append(n)
    o = []
    o.append("/* nd_gbi_leaf.h: GENERATED by 3ds/tools/gen_nd_gbi.py from the active gSP and gDP macros (F3DEX_GBI_2). Do not edit. */")
    o.append("#ifndef ND_GBI_LEAF_H")
    o.append("#define ND_GBI_LEAF_H")
    o.append("/* leaves: %d, compounds and aliases left as they are: %d */" % (len(leaf), len(comp)))
    for n in leaf:
        params, body = macros[n]
        pl = ", ".join(params)
        if n in DENY:
            o.append("#undef %s" % n)
            o.append("#define %s(%s) _Static_assert(0, \"%s has no native form (nd_gbi.h)\")" % (n, pl, n))
            continue
        o.append("#define ND_O_%s(%s) %s" % (n, pl, body))
        first = params[0]
        o.append("#undef %s" % n)
        tmp = "ND_O_%s(%s);" % (n, ", ".join(["_ndp++"] + params[1:]))
        o.append("#define %s(%s) { Gfx _ndt[ND_TMP_WORDS]; Gfx* _ndp = _ndt; %s nd_words((const unsigned*)_ndt, (unsigned)(_ndp - _ndt)); ND_O_%s(%s); }"
                 % (n, pl, tmp, n, pl))
    o.append("#endif")
    open(out, "w", newline="\n").write("\n".join(o) + "\n")
    print("leaves %d compounds %d denied %d" % (len(leaf), len(comp), len([n for n in leaf if n in DENY])))
    if rec_out:
        write_rec(macros, leaf, rec_out)


def write_rec(macros, leaf, out):
    """CORE-1: the record-mode form of every leaf (nd_rec.h). The leaf runs its bridge body into a temp list (ops = pointer increments of the body,
    slots = ops + the extra `_g ++` of the body, the 2-word TEXRECT), then nd_rec_leaf decodes the ops and writes the slots (other pkt) or
    writes no words (pkt in the main list). pkt is evaluated as often as the bridge (its uses in the body): the caller cursor moves the same."""
    o = []
    o.append("/* nd_rec_leaf.h: GENERATED by 3ds/tools/gen_nd_gbi.py (CORE-1). Do not edit. Included by nd_rec.h. */")
    o.append("#ifndef ND_REC_LEAF_H")
    o.append("#define ND_REC_LEAF_H")
    for n in leaf:
        if n in DENY:
            continue
        params, body = macros[n]
        pl = ", ".join(params)
        extra = len(re.findall(r"_g\s*\+\+", body))
        uses = len(re.findall(r"\b%s\b" % re.escape(params[0]), body))  # pkt uses in the body = the cursor advance of the bridge
        args = ", ".join(["_ndp++"] + params[1:])
        again = "".join("(void)(%s); " % params[0] for _ in range(max(uses, 1) - 1))
        o.append("#undef %s" % n)
        o.append("#define %s(%s) { Gfx* _ndq = (Gfx*)(%s); %sGfx _ndt[ND_TMP_WORDS]; Gfx* _ndp = _ndt; ND_O_%s(%s); "
                 "nd_rec_leaf(_ndq, _ndt, (unsigned)(_ndp - _ndt) + %d); }"
                 % (n, pl, params[0], again, n, args, extra))
    o.append("#endif")
    open(out, "w", newline="\n").write("\n".join(o) + "\n")
    print("rec leaves written %d" % len([n for n in leaf if n not in DENY]))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None)
