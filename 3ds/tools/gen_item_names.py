"""CH0: writes 3ds/stub_include/item_name_table.h, one name per item id in id order (row k is id k), from ver/us/build/include/item_enum.h.
Name = the enum tail in title case: ITEM_POWER_JUMP -> "Power Jump". Used by the Cheats folders (pm_dbg_game.c, pm_options.c).
Prints the row count (the count line goes to status_CH0.txt)."""
import re, os
root = os.path.join(os.path.dirname(__file__), '..', '..')
rows = []
for m in re.finditer(r'^\s*ITEM_(\w+)\s*=\s*(0x[0-9A-Fa-f]+)', open(os.path.join(root, 'ver/us/build/include/item_enum.h')).read(), re.M):
    name = ' '.join(w.capitalize() for w in m.group(1).split('_'))
    if int(m.group(2), 16) != len(rows): raise SystemExit('item ids are not 0..n-1 in order at %s: the table is indexed by id' % m.group(1))
    rows.append('    "%s", /* %s */' % (name, m.group(2).upper().replace('0X', '0x')))
out = os.path.join(root, '3ds/stub_include/item_name_table.h')
open(out, 'w').write('/* generated by tools/gen_item_names.py */\n' + '\n'.join(rows) + '\n')
print(len(rows), 'items')
