#!/usr/bin/env python3
"""hot_order.py: writes 3ds/ld/hot_order.ld, the hot .text group of the link (plan_hotcode.md stage HC2).

usage (repo root, PM_LANE=<L> for the normal lane and <L>_fncov built with PM_FNCOV=1):
  python 3ds/tools/hot_order.py <fncov log> [<fncov log> ...]

Input: the fncov logs of the census scenarios (fncov_mac01_det, fncov_kmr10_det, fncov_mac00_det; bench logs in
build3ds/azt/logs/), joined with the census map (addr -> name) of the lane <L>_fncov. Sizes and classes come from the normal
lane map and hotset.py (the M1 membership of hotset.json).
Output, in this order: each class A..I (hotset.json), the census functions that ran in class by calls per frame (mean over the
logs, a function that ran in some logs counts 0 in the others), then the citro3d/libctru members of the class by name
(not instrumented, so no counts). Functions in .text.unlikely (cold split) stay cold and are not listed.
A name the normal map does not have is an error (nothing written). Run hotset.py after: M2 reads this file.
"""
import argparse, sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hotset as H  # noqa: E402

OUT = H.REPO / "3ds" / "ld" / "hot_order.ld"
FNS, NAMES = {}, {}
LIBS = ("libcitro3d.a", "libctru.a")


def census_counts(logs):
    """-> (Counter name -> summed calls, frames) over the logs; frames = number of finished census frames."""
    tot, frames = Counter(), 0
    for log in logs:
        frames_here = {}
        with open(log, encoding="utf-8", errors="replace") as fh:
            for l in fh:
                m = H.re.search(r"fncov f(\d+) ((?:[0-9a-f]{8}:\d+ ?)+)", l)
                if m:
                    c = frames_here.setdefault(int(m.group(1)), Counter())
                    for tok in m.group(2).split():
                        a, n = tok.split(":")
                        c[int(a, 16)] += int(n)
                elif H.re.search(r"fncov f\d+ done", l):
                    frames_here.setdefault(int(H.re.search(r"fncov f(\d+) done", l).group(1)), Counter())
        if not frames_here:
            raise SystemExit("hot_order: no fncov frame in %s" % log)
        for f, c in frames_here.items():
            for a, n in c.items():
                tot[a] += n  # address for now; mapped to names below
            frames += 1
    return tot, frames


def main():
    ap = argparse.ArgumentParser(description="write 3ds/ld/hot_order.ld from fncov logs (HC2)")
    ap.add_argument("logs", nargs="+")
    ap.add_argument("--lane", default=H.os.environ.get("PM_LANE", ""))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    fmap = H.parse_map(H.lane_dir(a.lane, True) / "pm_3ds.map")       # census: addr -> name
    fns, names, calls, cg = H.model(a.lane)                            # normal: names, sizes, objects
    global FNS, NAMES
    FNS, NAMES = fns, names
    mem, missing = H.classes(fns, names, cg)
    if missing:
        print("hot_order: note, roots missing from the map (hotset.json): %s" % " ".join(missing))
    addr_n, frames = census_counts(a.logs)
    per = Counter()  # name -> calls per frame (sum over logs / frames)
    bad = []
    for ad, n in addr_n.items():
        e = fmap.get(ad)
        if not e:
            continue
        if e["name"] not in names:
            bad.append(e["name"])
            continue
        per[e["name"]] += n / float(frames)
    # A census function with no normal-map section was inlined in the normal build (the instrumented census build inlines less):
    # its code is inside a caller that is listed. Such names are counted and not written (not placeable).
    inl = sorted(set(bad))
    cls_of = {}
    lib_of = {}
    for c in H.CLASSES:
        for ad in sorted(mem[c], key=lambda x: fns[x]["name"]):
            e = fns[ad]
            if e["cold"]:
                continue
            if any(l in e["obj"] for l in LIBS):
                lib_of.setdefault(c, {})[e["name"]] = e["obj"]
            cls_of.setdefault(e["name"], c)
    out = []
    out += ["/* Generated by 3ds/tools/hot_order.py (plan_hotcode HC2) from %d census frame(s): %s."
           % (frames, ", ".join(Path(p).name for p in a.logs)),
           " * Hot .text group, by class (hotset.json), then calls per frame. Order matters: first in .text. Regenerate when the census"
           " changes; hotset.py M2 reads this file. */"]
    stale = []
    seen = set()
    for c in H.CLASSES + ["X"]:
        names_c = [n for n, k in cls_of.items() if k == c and per.get(n, 0) > 0]
        if c == "X":
            names_c = [n for n in per if n not in cls_of and per[n] > 0 and not all_cold(n)]
        names_c.sort(key=lambda n: (-per[n], n))
        libs = sorted(lib_of.get(c, {}).items()) if c != "X" else []
        if not names_c and not libs:
            continue
        out.append("\t\t/* class %s: %s */" % (c, H.CFG["classes"][c]["name"] if c in H.CFG["classes"] else "other, ran in the census"))
        for n in names_c:
            if n in seen:
                continue
            seen.add(n)
            out.append("\t\t*(.text.%s)  /* %.1f calls/frame, %d B */" % (n, per[n], fns_size(fns, names, n)))
        for n, obj in libs:
            if n in seen:
                continue
            seen.add(n)
            lib = "libcitro3d.a" if "libcitro3d.a" in obj else "libctru.a"
            out.append("\t\t*%s:*(.text.%s)" % (lib, n))
    text = "\n".join(out) + "\n"
    Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    print("hot_order: %d names (%d census calls/frame total) written to %s" % (len(seen), sum(per.values()), a.out))
    print("hot_order: %d census names not in the normal map (inlined there, not placed): %s" % (len(inl), " ".join(inl)))
    return 0


def all_cold(n):
    return all(FNS[x]["cold"] for x in NAMES[n])


def fns_size(fns, names, n):
    return sum(fns[x]["size"] for x in names.get(n, []) if not fns[x]["cold"])


if __name__ == "__main__":
    sys.exit(main())
