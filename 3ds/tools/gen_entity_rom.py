"""Regenerate 3ds/stub_include/entity_model_offsets.h: ROM ranges of entity_model_* segments, from ver/us/splat.yaml."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
segs = []  # (name, start) in file order, top-level segments only
cur = None
for line in (root / "ver/us/splat.yaml").read_text().splitlines():
    if line.startswith("  - "):
        cur = {"name": None, "start": None}
        segs.append(cur)
    if cur is None:
        continue
    m = re.match(r"^  (?:- )?name: (\S+)", line)
    if m:
        cur["name"] = m[1]
    m = re.match(r"^(?:  - |    )start: (0x[0-9A-Fa-f]+)", line)
    if m and cur["start"] is None:
        cur["start"] = int(m[1], 16)
out = ["/* Generated by 3ds/tools/gen_entity_rom.py. ROM file offsets. */"]
for i, s in enumerate(segs):
    if s["name"] and s["name"].startswith("entity_model_") and s["start"] is not None:
        end = next(t["start"] for t in segs[i + 1:] if t["start"] is not None)
        out.append(f"#define {s['name']}_ROM_START ((u8*)0x{s['start']:X})")
        out.append(f"#define {s['name']}_ROM_END   ((u8*)0x{end:X})")
(root / "3ds/stub_include/entity_model_offsets.h").write_text("\n".join(out) + "\n")
print(len(out) // 2)
