"""Regenerate 3ds/stub_include/effects/effect_defs.h (EffectID enum) from src/effects.yaml."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
names = []
for line in (root / "src/effects.yaml").read_text().splitlines():
    if line.startswith("- {}"):
        names.append(None)
    else:
        m = re.match(r"- name: (\w+)", line)
        if m:
            names.append(m[1])
out = ["/* Generated by 3ds/tools/gen_effect_ids.py. The effect runtime is not linked yet. */", "enum EffectID {"]
for i, n in enumerate(names):
    e = (n or f"{i:02X}").upper()
    out.append(f"    {e if e.startswith('EFFECT_') else 'EFFECT_' + e} = 0x{i:02X},")
out.append("};")
(root / "3ds/stub_include/effects/effect_defs.h").write_text("\n".join(out) + "\n")
print(len(names))
