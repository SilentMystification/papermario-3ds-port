#!/usr/bin/env python3
"""IMGFX: the 20 imgfx anim lists (assets/us/imgfx/<name>.json) as typed units, the C table nd_imgfx_tab.c.

Usage: gen_imgfx_tab.py <out.c> <json dir> [--check <rom> [--seed]]

A unit is (id, a, b): the typed word ND_FS_W0(id, a) and the b word, as nd_fs.h and nd_op.h define them.
units() ports tools/build/imgfx/imgfx_data.py:131-183 (the gfx list of the decomp build).
A vertex load b is 16 * sub (the first vertex of the chunk); the copy in imgfx.c adds vtxBufs[i].
--check reads the ROM (the imgfx_data segment at ROM_BASE) and compares its gfxCount units with units().
--seed adds 16 to b of unit 0 of shock before the compare (the check must fail).
"""
import json
import struct
import sys

NAMES = [
    "shock", "shiver", "vertical_pipe_curl", "horizontal_pipe_curl", "startle", "flutter_down", "unfurl",
    "get_in_bed", "spirit_capture", "unused_1", "unused_2", "unused_3", "tutankoopa_gather",
    "tutankoopa_swirl_2", "tutankoopa_swirl_1", "shuffle_cards", "flip_card_1", "flip_card_2", "flip_card_3",
    "cymbal_crush",
]
# imgfx.c ImgFXAnimOffsets, the same order (ImgFXAnimOffsets[type] + ROM_BASE is the ImgFXAnimHeader)
OFFS = [
    0x14358, 0x18200, 0x1A858, 0x1E830, 0x29458, 0x314E0, 0x33498, 0x38988, 0x39228, 0x5B7A8,
    0x7CF10, 0x86490, 0x96258, 0xA1820, 0xACDE8, 0xBBF68, 0xC0490, 0xC49B8, 0xC6150, 0xCA380,
]
ROM_BASE = 0x24B7F0  # data_rom_addrs.h imgfx_data_ROM_START
# F3DEX2 op byte -> typed id (G_VTX, G_TRI1, G_TRI2, G_ENDDL)
OPS = {0x01: "ND_FS_VTX", 0x05: "ND_FS_TRI1", 0x06: "ND_FS_TRI2", 0xDF: "ND_FS_END"}


def tri(i, j, k):
    return ((2 * i) & 0xFF) << 16 | ((2 * j) & 0xFF) << 8 | ((2 * k) & 0xFF)


def vtx(sub, n):
    return ("ND_FS_VTX", (n & 0xFF) << 12 | (n & 0x7F) << 1, 16 * sub)


def units(tris):
    out, chunk = [], []
    cur, just = 0, False
    m1 = m2 = mn = sub = old = 0
    while cur < len(tris):
        t1 = tris[cur]
        t2 = tris[cur + 1] if cur + 1 < len(tris) else None
        a = [v - sub for v in t1]
        b = [0, 0, 0] if t2 is None else [v - sub for v in t2]
        m1 = max(m1, *a)
        m2 = max(m2, *b)
        mn = min(mn, *a, *b)
        if m1 >= 32 and not just:
            out += [vtx(sub, min(32, m1 + 1))] + chunk
            chunk = []
            just = True
            sub += old - mn + 1
            mn = 32
            m1 = m2 = 0
            continue
        just = False
        if m2 >= 32 or t2 is None:
            chunk.append(("ND_FS_TRI1", tri(*a), 0))
            cur += 1
            old = m1
        else:
            chunk.append(("ND_FS_TRI2", tri(*a), tri(*b)))
            cur += 2
            old = max(m1, m2)
    return out + [vtx(sub, max(m1, m2) + 1)] + chunk + [("ND_FS_END", 0, 0)]


def rom_units(rom, off):
    """The ROM units of one list (None where a unit does not match a typed unit form)."""
    hdr = rom[ROM_BASE + off: ROM_BASE + off + 12]
    koff, goff, _vc, gc = struct.unpack(">IIHH", hdr)
    res = []
    for j in range(gc):
        p = ROM_BASE + goff + 8 * j
        w0, w1 = struct.unpack(">II", rom[p: p + 8])
        op = w0 >> 24
        if op == 0x01:
            d = w1 - koff
            res.append(("ND_FS_VTX", w0 & 0xFFFFFF, d // 12 * 16) if d >= 0 and d % 12 == 0 else None)
        elif op in (0x05, 0x06):
            res.append((OPS[op], w0 & 0xFFFFFF, w1))
        elif op == 0xDF:
            res.append(("ND_FS_END", 0, 0))
        else:
            res.append(None)
    return res


def write_c(path, lists):
    L = ["/* nd_imgfx_tab.c: generated by 3ds/tools/gen_imgfx_tab.py (IMGFX), git-ignored, do not edit. */",
         "#include <stdint.h>", '#include "nd_fs.h"', '#include "nd_imgfx.h"', ""]
    for name, us in zip(NAMES, lists):
        L.append("static const uint32_t u_%s[] = {" % name)
        for (uid, a, b) in us:
            L.append("    ND_FS_W0(%s, 0x%06x), 0x%08x," % (uid, a, b))
        L.append("};")
        L.append("")
    L.append("const uint32_t* const nd_imgfx_tab[ND_IMGFX_N] = { %s };" % ", ".join("u_" + n for n in NAMES))
    L.append("const uint16_t nd_imgfx_n[ND_IMGFX_N] = { %s };" % ", ".join(str(len(us)) for us in lists))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")


def main(argv):
    if len(argv) < 3:
        sys.exit("usage: gen_imgfx_tab.py <out.c> <json dir> [--check <rom> [--seed]]")
    out, jdir = argv[1], argv[2]
    rom_path, seed = None, False
    i = 3
    while i < len(argv):
        if argv[i] == "--check":
            rom_path = argv[i + 1]
            i += 2
        elif argv[i] == "--seed":
            seed = True
            i += 1
        else:
            sys.exit("unknown arg: " + argv[i])
    lists = []
    for name in NAMES:
        with open(jdir + "/" + name + ".json", encoding="utf-8") as f:
            d = json.load(f)
        lists.append(units([tuple(t) for t in d["triangles"]]))
    write_c(out, lists)
    if rom_path is None:
        return 0
    with open(rom_path, "rb") as f:
        rom = f.read()
    if seed:
        uid, a, b = lists[0][0]
        lists[0][0] = (uid, a, b + 16)
    for k, name in enumerate(NAMES):
        exp = lists[k]
        got = rom_units(rom, OFFS[k])
        for j in range(max(len(exp), len(got))):
            if j >= len(exp) or j >= len(got) or got[j] is None or got[j] != exp[j]:
                print("imgfx check FAIL %s unit %d" % (name, j))
                return 1
    print("imgfx check ok %d lists %d units" % (len(NAMES), sum(len(us) for us in lists)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
