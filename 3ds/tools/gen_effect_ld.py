"""Generate 3ds/stub_include/effect_ld_addrs.h and 3ds/effects.cmake from the effect table and build.ninja.
Effect code overlays are linked in, so ROM/VRAM ranges are empty. Graphics start is null: no DMA, no heap block."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
tbl = (root / "assets/us/effects/effect_table.c").read_text()
names, gfx = set(), set()
for n, g in re.findall(r"FX_ENTRY\((\w+), (\w+)\)", tbl):
    names.add(n); gfx.add(g)
out = ["/* Generated by 3ds/tools/gen_effect_ld.py. */", "#ifndef EFFECT_LD_ADDRS_H", "#define EFFECT_LD_ADDRS_H"]
for n in sorted(names):
    out += [f"#define effect_{n}_ROM_START ((u8*)1)", f"#define effect_{n}_ROM_END ((u8*)1)", f"#define effect_{n}_VRAM ((u8*)1)"]
for g in sorted(gfx):
    out += [f"#define {g}_ROM_START ((u8*)0)", f"#define {g}_ROM_END ((u8*)0)"]
out += ["#define effect_globals_ROM_START ((u8*)1)", "#define effect_globals_ROM_END ((u8*)1)", "#define effect_globals_VRAM ((u8*)1)", "#endif"]
(root / "3ds/stub_include/effect_ld_addrs.h").write_text("\n".join(out) + "\n")
ninja = (root / "build.ninja").read_text().replace(chr(92), "/")
srcs = sorted(set(re.findall(r"^build ver/us/build/(src/effects/[\w/]+\.c)\.o:", ninja, re.M)))
cm = ["# Generated by 3ds/tools/gen_effect_ld.py", "set(EFFECT_SRC"] + [f"    ${{DECOMP}}/{s}" for s in srcs] + [")"]
(root / "3ds/effects.cmake").write_text("\n".join(cm) + "\n")
print(len(names), len(gfx), len(srcs))

# fx_<name>: the N64 build has one asm trampoline per effect (load_effect, then jump to gEffectTable[id].entryPoint).
# This writes the same thing as C, typed from effect_macros.h.
defs = (root / "assets/us/effects/effect_macros.h").read_text()
macros = {m[0]: (m[1].strip(), m[2]) for m in re.findall(r"#define (EFFECT_DEF_\w+)\(func_name\) (.*?) func_name\((.*)\)", defs)}
dh = (root / "assets/us/effects/effect_defs.h").read_text()
calls = {fn: mac for mac, fn in re.findall(r"(EFFECT_DEF_\w+)\((fx_\w+)\);", dh)}
body = tbl.split("gEffectTable[] = {")[1]
entries = re.findall(r"^\s*(FX_ENTRY\((\w+)|\{\}),", body, re.M)
c = ["/* Generated by 3ds/tools/gen_effect_ld.py. Port equivalent of the splat asm in ver/us/build/asm/effects/<name>.s. */",
     '#include "common.h"', '#include "effects.h"', '#include "effects/effect_macros.h"', ""]
n = 0
for idx, (_, name) in enumerate(entries):
    if not name:
        continue
    ret, args = macros[calls["fx_" + name]]
    types = [a.strip() for a in args.split(",") if a.strip() and a.strip() != "void"]
    params = ", ".join(f"{t} a{i}" for i, t in enumerate(types)) or "void"
    use = ", ".join(f"a{i}" for i in range(len(types)))
    c += [f"{ret} {name}_main({', '.join(types) or 'void'});",
          f"{ret} fx_{name}({params}) {{", "    load_effect(0x%X);" % idx,
          f"    {'return ' if ret != 'void' else ''}{name}_main({use});", "}", ""]
    n += 1
(root / "3ds/src/effect_loads.c").write_text("\n".join(c))
print("loads", n)
