#!/usr/bin/env python3
"""R01: write 3ds/stub_include/data_rom_addrs.h from ver/us/splat.yaml. Run from the repo root.
These are DATA ranges the game reads from the ROM by offset (nuPiReadRom or dma_copy): a hand-typed value
(icon_ROM_START was 1 until H04) reads junk without a crash. START is the splat segment start, END is the next start
(the same value the real linker script gives). Add a stem to STEMS when the game reads a new data segment."""
import yaml
STEMS = ['charset', 'logos', 'title_bg_1', 'icon', 'imgfx_data']
# S19b: Lava Piranha animation scripts (s16 data, 00..24 hex). The game copies one of them to VINE_n_BASE by dma_copy.
# VRAM is the real N64 address (0x80234000). The callers always pass their own destination.
VINE_STEMS = ['world_model_anim_kzn_%02X' % i for i in range(0x25)]

def splat_ranges(path='ver/us/splat.yaml'):
    """name -> (start, end, type, top_level). End of a top level segment is the next top level start, else the next start."""
    Y = yaml.load(open(path), Loader=yaml.CSafeLoader)
    segs = []
    def walk(lst, top):
        for s in lst:
            if isinstance(s, dict):
                st, nm = s.get('start'), s.get('name') or s.get('dir')
                if isinstance(st, int) and nm:
                    segs.append((st, str(nm).replace('/', '_').replace('.', '_'), s.get('type', '?'), top))
                if 'subsegments' in s: walk(s['subsegments'], False)
            elif isinstance(s, list) and s and isinstance(s[0], int) and len(s) > 2 and isinstance(s[2], str):
                segs.append((s[0], s[2].replace('/', '_').replace('.', '_'), s[1], top))
    walk(Y['segments'], True)
    starts = sorted(set(s[0] for s in segs))
    tstarts = sorted(set(s[0] for s in segs if s[3]))
    out = {}
    for st, nm, ty, top in segs:
        e = next((x for x in (tstarts if top else starts) if x > st), 0x2800000)
        out.setdefault(nm, (st, e, ty, top))
    return out

if __name__ == '__main__':
    R = splat_ranges()
    o = ['/* Generated by 3ds/tools/gen_data_rom.py from ver/us/splat.yaml. Do not edit. ROM file offsets of data the game reads. */',
         '#ifndef DATA_ROM_ADDRS_H', '#define DATA_ROM_ADDRS_H']
    for n in STEMS:
        s, e = R[n][0], R[n][1]
        o += ['#define %s_ROM_START ((u8*)0x%X)' % (n, s), '#define %s_ROM_END   ((u8*)0x%X)' % (n, e)]
    for n in VINE_STEMS:
        s, e = R[n][0], R[n][1]
        o += ['#define %s_ROM_START ((u8*)0x%X)' % (n, s), '#define %s_ROM_END   ((u8*)0x%X)' % (n, e), '#define %s_VRAM ((u8*)0x80234000)' % n]
    o.append('#endif')
    open('3ds/stub_include/data_rom_addrs.h', 'w').write('\n'.join(o) + '\n')
    print('wrote', len(STEMS) + len(VINE_STEMS), 'ranges')
