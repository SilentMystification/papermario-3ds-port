#!/usr/bin/env python3
"""Generate 3ds/include/nd_nolist.h (NOLIST row, gate G8 of plan_endgame.md section 5).

Reads the display list macro names (g[sS]?[DS]P*) from the five GBI headers,
adds the typedef Gfx and the variable gMainGfxPos, and writes a header that
#undefs and #pragma GCC poisons each name. A converted file includes
nd_nolist.h as its last include; any later use of a name stops the build.

Usage: python 3ds/tools/gen_nolist.py   (run from any directory)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

HEADERS = [
    "include/PR/gbi.h",
    "include/gbi_custom.h",
    "include/PR/gs2dex.h",
    "include/PR/gt.h",
    "3ds/include/nd_gbi.h",
]

EXTRA = ["Gfx", "gMainGfxPos"]

DEFINE_RE = re.compile(r"^\s*#\s*define\s+(g[sS]?[DS]P[A-Za-z0-9_]*)", re.M)

OUT = os.path.join(ROOT, "3ds", "include", "nd_nolist.h")


def main():
    names = set()
    for rel in HEADERS:
        path = os.path.join(ROOT, rel)
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            text = f.read()
        names.update(DEFINE_RE.findall(text))
    names = sorted(names)
    for extra in EXTRA:
        if extra not in names:
            names.append(extra)

    lines = []
    lines.append("/* Generated by 3ds/tools/gen_nolist.py. Do not edit by hand.")
    lines.append(" * NOLIST row, gate G8: include this header LAST in a converted file.")
    lines.append(" * Every display list macro name, Gfx and gMainGfxPos is poisoned:")
    lines.append(" * a later use is a compile error. */")
    lines.append("#ifndef ND_NOLIST_H")
    lines.append("#define ND_NOLIST_H")
    lines.append("")
    for name in names:
        lines.append("#undef %s" % name)
        lines.append("#pragma GCC poison %s" % name)
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("nolist names %d" % len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
