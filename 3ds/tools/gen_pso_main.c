/* NPSO3: gen_pso_main.c, the host decision of every description. gen_pso_tab.py links it with pso_descs.c (the descriptions
 * and their names) and nd_decide.c, nd_tmpl.c, pm_comb.c. It writes the table file: the NdPsoOut bytes of each id (nd_pso_build
 * of its description; the layout is checked by a static assert in the table file) and nd_pso(id). */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "nd.h"
#include "nd_api.h"

extern const NdPsoDesc* const pso_descs[]; /* NULL-ended, in id order */
extern const char* const pso_names[];      /* NULL-ended, the names of pso_descs */

uint32_t f32tof24(float vf) { /* host copy of libctru f32tof24, as nd_decide_test.c has it */
    union { float f; uint32_t i; } v;
    v.f = vf;
    uint32_t sign = v.i >> 31, mant = (v.i & 0x7FFFFFu) >> 7;
    int exp = (int)((v.i >> 23) & 0xFF);
    if (exp == 0) return sign << 23;
    exp = exp - 127 + 63;
    if (exp < 0) return sign << 23;
    if (exp > 0x7F) return sign << 23 | 0x7Fu << 16;
    return mant | (uint32_t)exp << 16 | sign << 23;
}

/* same values as pm_f255 (pm_gpu.c:1717) */
void unpack8(unsigned c, float o[4]) { /* host copy, as nd_decide_test.c has it */
    o[0] = (float)((c >> 24) & 255u) / 255.f; o[1] = (float)((c >> 16) & 255u) / 255.f;
    o[2] = (float)((c >> 8) & 255u) / 255.f;  o[3] = (float)(c & 255u) / 255.f;
}

int main(int argc, char** argv) {
    unsigned n = 0, i, j, rows;
    FILE* f;
    if (argc != 2) {
        fprintf(stderr, "usage: psogen <out.c>\n");
        return 2;
    }
    while (pso_descs[n]) n++;
    rows = n ? n : 1;
    f = fopen(argv[1], "w");
    if (!f) return 1;
    fprintf(f, "/* nd_pso_tab.c: generated by gen_pso_tab.py (NPSO3), git-ignored, do not edit. */\n");
    fprintf(f, "#include \"nd.h\"\n#include \"nd_api.h\"\n");
    fprintf(f, "_Static_assert(sizeof(struct NdPsoOut) == %u, \"NdPsoOut layout\");\n", (unsigned)sizeof(struct NdPsoOut));
    fprintf(f, "static const uint8_t nd_pso_raw[%u][%u] __attribute__((aligned(4))) = {\n", rows, (unsigned)sizeof(struct NdPsoOut));
    if (n == 0) fprintf(f, "  { 0 }\n");
    for (i = 0; i < n; i++) {
        NdPsoOut o;
        const unsigned char* b = (const unsigned char*)&o;
        nd_pso_build(pso_descs[i], &o);
        fprintf(f, "  /* %u: %s */\n  {", i, pso_names[i]);
        for (j = 0; j < sizeof o; j++)
            fprintf(f, "%s%s%u", j ? "," : "", (j && j % 16 == 0) ? "\n    " : "", b[j]);
        fprintf(f, "\n  },\n");
    }
    fprintf(f, "};\n");
    /* NPSO2D: the descriptions by id, and the ids sorted by (cw0, cw1) (insertion sort, equal keys keep id order) for nd_pso_find */
    if (n > 1024) { fprintf(stderr, "gen_pso_main: %u descs, the sort index holds 1024\n", n); fclose(f); return 1; }
    fprintf(f, "const NdPsoDesc nd_pso_dsc[%u] = {\n", rows);
    if (n == 0) fprintf(f, "  { 0 }\n");
    for (i = 0; i < n; i++) {
        const NdPsoDesc* d = pso_descs[i];
        fprintf(f, "  { %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu, %uu },\n",
                (unsigned)d->cw0, (unsigned)d->cw1, (unsigned)d->omh, (unsigned)d->oml, (unsigned)d->geom, (unsigned)d->key_c, (unsigned)d->key_s,
                (unsigned)d->conv_k4, (unsigned)d->tex_on, (unsigned)d->use_t1, (unsigned)d->t1_valid, (unsigned)d->dual_on, (unsigned)d->box_prod,
                (unsigned)d->box_folded, (unsigned)d->comb_set, (unsigned)d->comb_alpha_shade, (unsigned)d->leg_prev, (unsigned)d->vprim,
                (unsigned)d->zimg, (unsigned)d->plod);
    }
    fprintf(f, "};\n");
    {
        static uint16_t ord[1024];
        for (i = 0; i < n; i++) {
            unsigned k = i;
            while (k > 0) {
                const NdPsoDesc* a = pso_descs[ord[k - 1]];
                const NdPsoDesc* b = pso_descs[i];
                if (a->cw0 < b->cw0 || (a->cw0 == b->cw0 && a->cw1 <= b->cw1)) break;
                k--;
            }
            for (j = i; j > k; j--) ord[j] = ord[j - 1];
            ord[k] = (uint16_t)i;
        }
        fprintf(f, "const uint16_t nd_pso_ord[%u] = {", rows);
        if (n == 0) fprintf(f, " 0");
        for (i = 0; i < n; i++) fprintf(f, "%s%u", i ? "," : " ", (unsigned)ord[i]);
        fprintf(f, " };\n");
    }
    fprintf(f, "const unsigned nd_pso_n = %u;\n", n);
    fprintf(f, "const NdPsoOut* nd_pso(NdPso id) { return id < nd_pso_n ? (const NdPsoOut*)(const void*)nd_pso_raw[id] : 0; }\n");
    if (fclose(f) != 0) return 1;
    return 0;
}
