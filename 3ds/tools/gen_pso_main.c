/* NPSO3: gen_pso_main.c, the host decision of every description. gen_pso_tab.py links it with pso_descs.c (the descriptions
 * and their names) and nd_decide.c, nd_tmpl.c, pm_comb.c. It writes the table file: the NdPsoOut bytes of each id (nd_pso_build
 * of its description; the layout is checked by a static assert in the table file) and nd_pso(id). NPSO2D: also the lookup table of
 * nd_pso_find: nd_pso_key (one key per distinct in-equality set, sorted by (cw0, cw1), 28 B each), nd_pso_small (the small part of each
 * key's NdCombOut, index = key index), nd_pso_plan (the distinct plans as NdPlanRec, the stages in nd_pso_stage_raw) and nd_pso_nkey. The device reads
 * only these: nd_pso() is not called there, so its bytes are dropped by the linker. */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "nd.h"
#include "nd_api.h"

extern const NdPsoDesc* const pso_descs[]; /* NULL-ended, in id order */
extern const char* const pso_names[];      /* NULL-ended, the names of pso_descs */

uint32_t f32tof24(float vf) { /* host copy of libctru f32tof24, as nd_decide_test.c has it */
    union { float f; uint32_t i; } v;
    v.f = vf;
    uint32_t sign = v.i >> 31, mant = (v.i & 0x7FFFFFu) >> 7;
    int exp = (int)((v.i >> 23) & 0xFF);
    if (exp == 0) return sign << 23;
    exp = exp - 127 + 63;
    if (exp < 0) return sign << 23;
    if (exp > 0x7F) return sign << 23 | 0x7Fu << 16;
    return mant | (uint32_t)exp << 16 | sign << 23;
}

/* same values as pm_f255 (pm_gpu.c:1717) */
void unpack8(unsigned c, float o[4]) { /* host copy, as nd_decide_test.c has it */
    o[0] = (float)((c >> 24) & 255u) / 255.f; o[1] = (float)((c >> 16) & 255u) / 255.f;
    o[2] = (float)((c >> 8) & 255u) / 255.f;  o[3] = (float)(c & 255u) / 255.f;
}

static NdPsoOut outs[1024];
static NdPsoKey keys[1024];
static unsigned kid[1024]; /* the id of the first description of each key, in key order */
static NdPsoSmall smalls[1024];
static PmPlan plans[256];
static NdPlanRec recs[256];
static PmTevStage stages[256]; /* index 0: the all-zero stage */
static unsigned ns = 1;

/* the index of a stage in stages (added when new, memcmp of the whole PmTevStage); -1 when the table would exceed 255 */
static int stage_idx(const PmTevStage* st) {
    for (unsigned q = 0; q < ns; q++) if (!memcmp(&stages[q], st, sizeof *st)) return (int)q;
    if (ns == 256) return -1;
    stages[ns] = *st;
    return (int)ns++;
}

static void dump(FILE* f, const unsigned char* b, size_t len) {
    for (size_t j = 0; j < len; j++)
        fprintf(f, "%s%s%u", j ? "," : "", (j && j % 16 == 0) ? "\n    " : "", b[j]);
}

/* the small part of a comb: the int fields must fit int8 (checked here, not truncated) */
static int small_of(const NdCombOut* c, NdPsoSmall* s, const char* name) {
    const int v[10] = { c->leg, c->mode5, c->pat, c->use, c->why, c->cyc, c->dual, c->plan_on, c->cc_on, c->env_on };
    for (int q = 0; q < 10; q++)
        if (v[q] < -128 || v[q] > 127) { fprintf(stderr, "gen_pso_main: field %d of %s does not fit int8 (%d)\n", q, name, v[q]); return 0; }
    memset(s, 0, sizeof *s);
    s->cc = c->cc;
    s->leg = (int8_t)c->leg; s->mode5 = (int8_t)c->mode5; s->pat = (int8_t)c->pat; s->use = (int8_t)c->use; s->why = (int8_t)c->why;
    s->cyc = (int8_t)c->cyc; s->dual = (int8_t)c->dual; s->plan_on = (int8_t)c->plan_on; s->cc_on = (int8_t)c->cc_on; s->env_on = (int8_t)c->env_on;
    return 1;
}

int main(int argc, char** argv) {
    unsigned n = 0, i, rows, nk = 0, np = 0, t, u, q;
    FILE* f;
    if (argc != 2) {
        fprintf(stderr, "usage: psogen <out.c>\n");
        return 2;
    }
    while (pso_descs[n]) n++;
    rows = n ? n : 1;
    if (n > 1024) { fprintf(stderr, "gen_pso_main: %u descs, the tables hold 1024\n", n); return 1; }
    f = fopen(argv[1], "w");
    if (!f) return 1;
    fprintf(f, "/* nd_pso_tab.c: generated by gen_pso_tab.py (NPSO3), git-ignored, do not edit. */\n");
    fprintf(f, "#include \"nd.h\"\n#include \"nd_api.h\"\n");
    fprintf(f, "_Static_assert(sizeof(struct NdPsoOut) == %u, \"NdPsoOut layout\");\n", (unsigned)sizeof(struct NdPsoOut));
    fprintf(f, "static const uint8_t nd_pso_raw[%u][%u] __attribute__((aligned(4))) = {\n", rows, (unsigned)sizeof(struct NdPsoOut));
    if (n == 0) fprintf(f, "  { 0 }\n");
    for (i = 0; i < n; i++) {
        nd_pso_build(pso_descs[i], &outs[i]);
        fprintf(f, "  /* %u: %s */\n  {", i, pso_names[i]);
        dump(f, (const unsigned char*)&outs[i], sizeof outs[i]);
        fprintf(f, "\n  },\n");
    }
    fprintf(f, "};\n");
    /* NPSO2D: one key per distinct in-equality set (kid: its first id; a second id with the same key must have the same comb) */
    for (i = 0; i < n; i++) {
        const NdPsoDesc* d = pso_descs[i];
        NdPsoKey k;
        memset(&k, 0, sizeof k);
        k.cw0 = d->cw0; k.cw1 = d->cw1; k.omh = d->omh; k.key_c = d->key_c; k.key_s = d->key_s;
        k.conv_k4 = (uint8_t)d->conv_k4; k.plod = d->plod; k.vprim = d->vprim;
        k.flags = nd_pso_flags(d->tex_on, d->use_t1, d->t1_valid, d->dual_on, d->box_prod, d->box_folded, d->comb_set, d->comb_alpha_shade);
        if (d->conv_k4 > 255u) { fprintf(stderr, "gen_pso_main: conv_k4 of %s does not fit a byte\n", pso_names[i]); fclose(f); return 1; }
        for (u = 0; u < nk; u++) if (!memcmp(&keys[u], &k, sizeof k - sizeof k.si)) break;
        if (u < nk) {
            if (memcmp(&outs[kid[u]].comb, &outs[i].comb, sizeof(NdCombOut))) { fprintf(stderr, "gen_pso_main: one key with two combs (%s)\n", pso_names[i]); fclose(f); return 1; }
            continue;
        }
        q = nk;
        while (q > 0 && (keys[q - 1].cw0 > k.cw0 || (keys[q - 1].cw0 == k.cw0 && keys[q - 1].cw1 > k.cw1))) {
            keys[q] = keys[q - 1]; kid[q] = kid[q - 1]; q--;
        }
        keys[q] = k; kid[q] = i; nk++;
    }
    if (nk > 65535u) { fprintf(stderr, "gen_pso_main: %u keys\n", nk); fclose(f); return 1; }
    /* the small parts (index = key index) and the distinct plans */
    for (t = 0; t < nk; t++) {
        const NdCombOut* c = &outs[kid[t]].comb;
        NdPsoSmall* s = &smalls[t];
        keys[t].si = (uint16_t)t;
        if (!small_of(c, s, pso_names[kid[t]])) { fclose(f); return 1; }
        s->pi = 0;
        if (c->plan_on) {
            for (u = 0; u < np; u++) if (!memcmp(&plans[u], &c->plan, sizeof(PmPlan))) break;
            if (u == np) {
                if (np == 256) { fprintf(stderr, "gen_pso_main: more than 256 plans\n"); fclose(f); return 1; }
                {
                    NdPlanRec* r = &recs[np];
                    int si;
                    memset(r, 0, sizeof *r);
                    r->n = c->plan.n; r->buf = c->plan.buf; r->vtx = c->plan.vtx;
                    r->bufname = c->plan.bufname; r->vtxname = c->plan.vtxname;
                    r->uses_tex = c->plan.uses_tex; r->uses_sha = c->plan.uses_sha; r->uses_tex1 = c->plan.uses_tex1; r->uses_noise = c->plan.uses_noise;
                    memcpy(r->ks, c->plan.ks, sizeof r->ks); memcpy(r->fold, c->plan.fold, sizeof r->fold);
                    for (unsigned q = 0; q < 6; q++) {
                        si = stage_idx(&c->plan.st[q]);
                        if (si < 0) { fprintf(stderr, "gen_pso_main: more than 255 distinct stages\n"); fclose(f); return 1; }
                        r->si[q] = (uint8_t)si;
                    }
                    plans[np] = c->plan;
                    np++;
                }
            }
            s->pi = (uint8_t)u;
        }
    }
    fprintf(f, "const uint8_t nd_pso_stage_raw[%u][%u] __attribute__((aligned(4))) = {\n", ns, (unsigned)sizeof(PmTevStage));
    for (u = 0; u < ns; u++) {
        fprintf(f, "  {");
        dump(f, (const unsigned char*)&stages[u], sizeof(PmTevStage));
        fprintf(f, "},\n");
    }
    fprintf(f, "};\n");
    fprintf(f, "const NdPlanRec nd_pso_plan[%u] = {\n", np ? np : 1);
    if (np == 0) fprintf(f, "  { 0 }\n");
    for (u = 0; u < np; u++) {
        const NdPlanRec* r = &recs[u];
        fprintf(f, "  { %d, %uu, %uu, %u, %u, %u, %u, %u, %u, { { %u, %u, %u, %u, %u }, { %u, %u, %u, %u, %u }, { %u, %u, %u, %u, %u }, { %u, %u, %u, %u, %u } }, { %u, %u, %u, %u, %u, %u }, { %u, %u, %u, %u, %u, %u } },\n",
                r->n, r->buf, r->vtx, r->bufname, r->vtxname, r->uses_tex, r->uses_sha, r->uses_tex1, r->uses_noise,
                r->ks[0][0], r->ks[0][1], r->ks[0][2], r->ks[0][3], r->ks[0][4], r->ks[1][0], r->ks[1][1], r->ks[1][2], r->ks[1][3], r->ks[1][4],
                r->ks[2][0], r->ks[2][1], r->ks[2][2], r->ks[2][3], r->ks[2][4], r->ks[3][0], r->ks[3][1], r->ks[3][2], r->ks[3][3], r->ks[3][4],
                r->fold[0], r->fold[1], r->fold[2], r->fold[3], r->fold[4], r->fold[5], r->si[0], r->si[1], r->si[2], r->si[3], r->si[4], r->si[5]);
    }
    fprintf(f, "};\n");
    fprintf(f, "const NdPsoKey nd_pso_key[%u] = {\n", nk ? nk : 1);
    if (nk == 0) fprintf(f, "  { 0 }\n");
    for (t = 0; t < nk; t++) {
        const NdPsoKey* k = &keys[t];
        fprintf(f, "  { %uu, %uu, %uu, %uu, %uu, %u, %u, %u, %u, %u },\n", (unsigned)k->cw0, (unsigned)k->cw1, (unsigned)k->omh, (unsigned)k->key_c,
                (unsigned)k->key_s, (unsigned)k->conv_k4, (unsigned)k->plod, (unsigned)k->vprim, (unsigned)k->flags, (unsigned)k->si);
    }
    fprintf(f, "};\n");
    fprintf(f, "const NdPsoSmall nd_pso_small[%u] = {\n", nk ? nk : 1);
    if (nk == 0) fprintf(f, "  { 0 }\n");
    for (t = 0; t < nk; t++) {
        const NdPsoSmall* s = &smalls[t];
        fprintf(f, "  { %uu, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %u, 0 },\n", (unsigned)s->cc, s->leg, s->mode5, s->pat, s->use, s->why, s->cyc,
                s->dual, s->plan_on, s->cc_on, s->env_on, (unsigned)s->pi);
    }
    fprintf(f, "};\n");
    fprintf(f, "const unsigned nd_pso_nkey = %u;\n", nk);
    fprintf(f, "const unsigned nd_pso_n = %u;\n", n);
    fprintf(f, "const NdPsoOut* nd_pso(NdPso id) { return id < nd_pso_n ? (const NdPsoOut*)(const void*)nd_pso_raw[id] : 0; }\n");
    if (fclose(f) != 0) return 1;
    fprintf(stderr, "gen_pso_main: descs %u keys %u plans %u\n", n, nk, np);
    return 0;
}
