/* NPSO3: gen_pso_main.c, the host decision of every description. gen_pso_tab.py links it with pso_descs.c (the descriptions
 * and their names) and nd_decide.c, nd_tmpl.c, pm_comb.c. It writes the table file: the NdPsoOut bytes of each id (nd_pso_build
 * of its description; the layout is checked by a static assert in the table file) and nd_pso(id). */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "nd.h"
#include "nd_api.h"

extern const NdPsoDesc* const pso_descs[]; /* NULL-ended, in id order */
extern const char* const pso_names[];      /* NULL-ended, the names of pso_descs */

uint32_t f32tof24(float vf) { /* host copy of libctru f32tof24, as nd_decide_test.c has it */
    union { float f; uint32_t i; } v;
    v.f = vf;
    uint32_t sign = v.i >> 31, mant = (v.i & 0x7FFFFFu) >> 7;
    int exp = (int)((v.i >> 23) & 0xFF);
    if (exp == 0) return sign << 23;
    exp = exp - 127 + 63;
    if (exp < 0) return sign << 23;
    if (exp > 0x7F) return sign << 23 | 0x7Fu << 16;
    return mant | (uint32_t)exp << 16 | sign << 23;
}

int main(int argc, char** argv) {
    unsigned n = 0, i, j, rows;
    FILE* f;
    if (argc != 2) {
        fprintf(stderr, "usage: psogen <out.c>\n");
        return 2;
    }
    while (pso_descs[n]) n++;
    rows = n ? n : 1;
    f = fopen(argv[1], "w");
    if (!f) return 1;
    fprintf(f, "/* nd_pso_tab.c: generated by gen_pso_tab.py (NPSO3), git-ignored, do not edit. */\n");
    fprintf(f, "#include \"nd.h\"\n#include \"nd_api.h\"\n");
    fprintf(f, "_Static_assert(sizeof(struct NdPsoOut) == %u, \"NdPsoOut layout\");\n", (unsigned)sizeof(struct NdPsoOut));
    fprintf(f, "static const uint8_t nd_pso_raw[%u][%u] __attribute__((aligned(4))) = {\n", rows, (unsigned)sizeof(struct NdPsoOut));
    if (n == 0) fprintf(f, "  { 0 }\n");
    for (i = 0; i < n; i++) {
        NdPsoOut o;
        const unsigned char* b = (const unsigned char*)&o;
        nd_pso_build(pso_descs[i], &o);
        fprintf(f, "  /* %u: %s */\n  {", i, pso_names[i]);
        for (j = 0; j < sizeof o; j++)
            fprintf(f, "%s%s%u", j ? "," : "", (j && j % 16 == 0) ? "\n    " : "", b[j]);
        fprintf(f, "\n  },\n");
    }
    fprintf(f, "};\n");
    fprintf(f, "const unsigned nd_pso_n = %u;\n", n);
    fprintf(f, "const NdPsoOut* nd_pso(NdPso id) { return id < nd_pso_n ? (const NdPsoOut*)(const void*)nd_pso_raw[id] : 0; }\n");
    if (fclose(f) != 0) return 1;
    return 0;
}
