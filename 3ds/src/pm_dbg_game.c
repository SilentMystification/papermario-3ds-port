/* CH6: Moon Jump (RAM only, not saved). The launch switch moonjump turns it on at boot. Per step (pm_warp_tick, after the game logic) while
 * A is held and Mario jumps or falls: the upward velocity is at least 4 and the other integrator terms are zero, so the jump floats. */
static int moon_on = -1;
int pm_cheat_moon_get(void) {
    if (moon_on < 0) moon_on = pm_debug_has("moonjump") ? 1 : 0;
    return moon_on;
}
void pm_cheat_moon_set(int on) {
    moon_on = on ? 1 : 0;
    pm_log("cheat: moon jump %s", moon_on ? "on" : "off");
}
/* CH7: batch 1 cheats (RAM only): bits in cheat_bits, set at boot by the launch value cheats=<list> (hp, fp, sp, nobattle, speed, comma separated).
 * The tick runs once per step (pm_warp_tick). Each cheat logs once when it first runs, and a refill logs its change. */
enum { CHB_HP = 1, CHB_FP = 2, CHB_SP = 4, CHB_NOBATTLE = 8, CHB_SPEED = 16 };
static const char* const cheat_name[5] = { "infinite HP", "infinite FP", "infinite star power", "no battles", "speed x2" };
static const int cheat_bit[5] = { CHB_HP, CHB_FP, CHB_SP, CHB_NOBATTLE, CHB_SPEED };
static int cheat_bits = -1, cheat_seen;
/* a whole token of the comma list (sp is not speed) */
static int has_token(const char* list, const char* tok) {
    size_t n = strlen(tok);
    for (const char* p = list; (p = strstr(p, tok)) != NULL; p += n)
        if ((p == list || p[-1] == ',') && (p[n] == 0 || p[n] == ',')) return 1;
    return 0;
}
static void cheat_init(void) {
    char v[96];
    if (cheat_bits >= 0) return;
    cheat_bits = 0;
    if (pm_debug_value("cheats", v, sizeof v)) {
        if (has_token(v, "hp")) cheat_bits |= CHB_HP;
        if (has_token(v, "fp")) cheat_bits |= CHB_FP;
        if (has_token(v, "sp")) cheat_bits |= CHB_SP;
        if (has_token(v, "nobattle")) cheat_bits |= CHB_NOBATTLE;
        if (has_token(v, "speed")) cheat_bits |= CHB_SPEED;
    }
}
int pm_cheat_get(int k) { cheat_init(); return (cheat_bits & cheat_bit[k]) != 0; }
void pm_cheat_set(int k, int on) {
    cheat_init();
    if (on) cheat_bits |= cheat_bit[k]; else cheat_bits &= ~cheat_bit[k];
    pm_log("cheat: %s %s", cheat_name[k], on ? "on" : "off");
}
void pm_cheat_tick(void) {
    PlayerStatus* ps = &gPlayerStatus;
    PlayerData* p = &gPlayerData;
    cheat_init();
    if (cheat_bits & CHB_HP && p->curHP != p->curMaxHP) { pm_log("cheat: infinite HP refill %d -> %d", (int)p->curHP, (int)p->curMaxHP); p->curHP = p->curMaxHP; }
    if (cheat_bits & CHB_FP && p->curFP != p->curMaxFP) { pm_log("cheat: infinite FP refill %d -> %d", (int)p->curFP, (int)p->curMaxFP); p->curFP = p->curMaxFP; }
    if (cheat_bits & CHB_SP) p->starPower = (s16)(p->maxStarPower * 256);
    if (cheat_bits & CHB_NOBATTLE) gCurrentEncounter.battleTriggerCooldown = 2;
    if (cheat_bits & CHB_SPEED) { ps->walkSpeed *= 2.0f; ps->runSpeed *= 2.0f; } /* the action code sets the speeds each step, so this does not compound */
    if ((cheat_bits & ~cheat_seen) != 0) {
        int k;
        for (k = 0; k < 5; k++) if ((cheat_bits & ~cheat_seen) & cheat_bit[k]) pm_log("cheat: %s active, star power %d, walk %.2f", cheat_name[k], (int)p->starPower, ps->walkSpeed);
        cheat_seen = cheat_bits;
    }
    /* MOON: each new press of A in the air starts a normal jump again: set_action_state(ACTION_STATE_JUMP) at the press, so the next step's
     * action update runs initialize_jump (a full jump start, GravityParamsStartJump). Between presses gravity runs as it does, with no per-step
     * override. A press counts when the step before had A released and Mario in the air. (The old hold kept the jump alive past timeInAir 100,
     * where update_player puts Mario back on lastGoodPos.) */
    {
        static int moon_held, moon_air;
        const int air = (ps->flags & (PS_FLAG_JUMPING | PS_FLAG_FALLING)) != 0;
        const int held = (ps->curButtons & BUTTON_A) != 0;
        const int press = held && !moon_held && moon_air;
        moon_held = held;
        moon_air = air;
        if (!air) return;
        if (!pm_cheat_moon_get()) {
            pm_log_d("cheat: jump y %.1f", ps->pos.y);
            return;
        }
        if (!press) {
            pm_log_d("cheat: moon jump y %.1f", ps->pos.y);
            return;
        }
        set_action_state(ACTION_STATE_JUMP); /* the normal jump start: the next step's action update runs initialize_jump (start integrators, substate, jump origin, timeInAir 0, animation, sound) */
        pm_log("cheat: moon jump restart y %.1f", ps->pos.y);
    }
}

/* CH8: further cheat rows (RAM only, Cheats tab): 0 boots level, 1 hammer level, 2 max star spirits, 3 star pieces, 4 story, 5 inventory item
 * (a row of the consumables), 6 fill the inventory with it, 7 save position, 8 load position (same map), 9 instant win (battle).
 * Frame advance is the FADV row above (pm_fa_get, pm_fa_set): the loop in pm_main.c steps the game with R while it is on. */
static const char* const ch8_name[6] = { "boots level", "hammer level", "max star spirits", "star pieces", "story", "inventory item" };
static int story_i, inv_row, pos_saved, save_area, save_map, save_entry;
static float save_x, save_y, save_z;
const char* pm_dbgg_ch8_text(int k) {
    static char b[48];
    PlayerData* p = &gPlayerData;
    switch (k) {
        case 0: snprintf(b, sizeof b, "%d", (int)p->bootsLevel); break;
        case 1: snprintf(b, sizeof b, "%d", (int)p->hammerLevel); break;
        case 2: snprintf(b, sizeof b, "%d", (int)p->maxStarPower); break;
        case 3: snprintf(b, sizeof b, "%d", (int)p->starPieces); break;
        case 4: snprintf(b, sizeof b, "%s", pm_warp_story_label(story_i)); break;
        case 5: snprintf(b, sizeof b, "%s", pm_item_name(pm_dbgg_spawn_id(inv_row))); break;
        case 7: snprintf(b, sizeof b, pos_saved ? "saved" : "A: save"); break;
        case 8: snprintf(b, sizeof b, pos_saved ? "A: load" : "none saved"); break;
        default: snprintf(b, sizeof b, "A: do"); break;
    }
    return b;
}
/* dir steps a value row (wrap at both ends), 4 and 5 step the story and the item lists */
void pm_dbgg_ch8_step(int k, int dir) {
    PlayerData* p = &gPlayerData;
    int v, n;
    switch (k) {
        case 0: v = p->bootsLevel + dir; if (v < -1) v = 2; if (v > 2) v = -1; p->bootsLevel = (s8)v; break;
        case 1: v = p->hammerLevel + dir; if (v < -1) v = 2; if (v > 2) v = -1; p->hammerLevel = (s8)v; break;
        case 2: v = p->maxStarPower + dir; if (v < 0) v = 7; if (v > 7) v = 0; p->maxStarPower = (s8)v; break;
        case 3: v = p->starPieces + dir; if (v < 0) v = 255; if (v > 255) v = 0; p->starPieces = (u8)v; break;
        case 4: n = pm_warp_story_n(); story_i = ((story_i + dir) % n + n) % n; pm_warp_story_apply(story_i); return;
        case 5: n = pm_dbgg_spawn_count(); inv_row = ((inv_row + dir) % n + n) % n; return;
        default: return;
    }
    pm_log("cheat: %s %d", ch8_name[k], v);
}
void pm_dbgg_ch8_act(int k) {
    PlayerData* p = &gPlayerData;
    PlayerStatus* ps = &gPlayerStatus;
    int j, id;
    switch (k) {
        case 0: case 1: case 2: case 3: case 4: case 5: pm_dbgg_ch8_step(k, 1); return;
        case 6: /* fill: all 10 slots get the item of the row */
            id = pm_dbgg_spawn_id(inv_row);
            for (j = 0; j < 10; j++) p->invItems[j] = (s16)id;
            pm_log("cheat: inventory filled with 0x%03X %s", id, pm_item_name(id));
            return;
        case 7: /* save: area, map, entry and the position, RAM only */
            save_area = gGameStatusPtr->areaID; save_map = gGameStatusPtr->mapID; save_entry = gGameStatusPtr->entryID;
            save_x = ps->pos.x; save_y = ps->pos.y; save_z = ps->pos.z; pos_saved = 1;
            pm_log("cheat: position saved, map %d:%d entry %d", save_area, save_map, save_entry);
            return;
        case 8: /* load: only on the saved map, else a message */
            if (!pos_saved) { pm_menu_msg("No position saved"); return; }
            if (gGameStatusPtr->areaID != save_area || gGameStatusPtr->mapID != save_map) { pm_log_w("cheat: position is for another map"); pm_menu_msg("Saved position is on another map"); return; }
            ps->pos.x = save_x; ps->pos.y = save_y; ps->pos.z = save_z;
            pm_log("cheat: position loaded x %.1f y %.1f z %.1f", save_x, save_y, save_z);
            return;
        default: /* instant win: the battle victory state, in battle only */
            if (get_game_mode() != GAME_MODE_BATTLE) { pm_menu_msg("Instant win needs a battle"); return; }
            btl_set_state(BATTLE_STATE_VICTORY);
            pm_log("cheat: instant win");
            return;
    }
}

/* owned and total of a group: 0 partners, 1 badges, 2 key items */
void pm_dbgg_count(int g, int* have, int* total) {
    int i, h = 0, t = 0;
    PlayerData* p = &gPlayerData;
    if (g == 0) {
        for (i = 1; i < 12; i++) { t++; h += p->partners[i].enabled != 0; }
    } else {
        for (i = 1; i < (int)ARRAY_COUNT(gItemTable); i++) {
            int j, n = g == 1 ? (int)ARRAY_COUNT(p->badges) : (int)ARRAY_COUNT(p->keyItems);
            s16* a = g == 1 ? p->badges : p->keyItems;
            if (!is_item(i, g == 1 ? ITEM_TYPE_FLAG_BADGE : ITEM_TYPE_FLAG_KEY)) continue;
            t++;
            for (j = 0; j < n; j++) if (a[j] == i) { h++; break; }
        }
    }
    *have = h; *total = t;
}

void pm_dbgg_give(int g) {
    int i, j;
    PlayerData* p = &gPlayerData;
    if (g == 0) { /* 11 partners; level 0 stays the base level */
        for (i = 1; i < 12; i++) p->partners[i].enabled = 1;
        if (p->curPartner == 0) p->curPartner = PARTNER_GOOMBARIO;
    } else {
        int n = g == 1 ? (int)ARRAY_COUNT(p->badges) : (int)ARRAY_COUNT(p->keyItems);
        s16* a = g == 1 ? p->badges : p->keyItems;
        for (i = 1; i < (int)ARRAY_COUNT(gItemTable); i++) {
            if (!is_item(i, g == 1 ? ITEM_TYPE_FLAG_BADGE : ITEM_TYPE_FLAG_KEY)) continue;
            for (j = 0; j < n; j++) if (a[j] == i) break;
            if (j < n) continue; /* owned */
            for (j = 0; j < n; j++) if (a[j] == ITEM_NONE) { a[j] = i; break; }
        }
    }
    pm_dbgg_count(g, &i, &j);
    pm_log("dbggame: give %d -> owned %d of %d", g, i, j);
}

int pm_dbgg_stat_get(int k) {
    PlayerData* p = &gPlayerData;
    switch (k) {
        case PM_DBG_MAXHP: return p->hardMaxHP;
        case PM_DBG_MAXFP: return p->hardMaxFP;
        case PM_DBG_BP: return p->maxBP;
        case PM_DBG_LEVEL: return pm_dbgg_level_calc(); /* read only: computed from the stats */
        case PM_DBG_COINS: return p->coins;
        default: return p->starPoints;
    }
}

/* dir steps by the table step (wraps at both ends); HP and FP are refilled */
void pm_dbgg_stat_step(int k, int dir) {
    PlayerData* p = &gPlayerData;
    int v = pm_dbgg_stat_get(k) + dir * rg[k].st;
    if (dir > 0 && pm_dbgg_stat_get(k) >= rg[k].hi) v = rg[k].lo;
    if (dir < 0 && pm_dbgg_stat_get(k) <= rg[k].lo) v = rg[k].hi;
    if (v < rg[k].lo) v = rg[k].lo;
    if (v > rg[k].hi) v = rg[k].hi;
    switch (k) {
        case PM_DBG_MAXHP: p->hardMaxHP = v; enforce_hpfp_limits(); p->curHP = p->curMaxHP; break;
        case PM_DBG_MAXFP: p->hardMaxFP = v; enforce_hpfp_limits(); p->curFP = p->curMaxFP; break;
        case PM_DBG_BP: p->maxBP = v; break;
        case PM_DBG_LEVEL: p->level = v; break;
        case PM_DBG_COINS: p->coins = v; break;
        default: p->starPoints = v; break;
    }
    if (k <= PM_DBG_BP) level_sync(); /* a stat row changed: the game level follows */
    pm_log("dbggame: stat %d = %d", k, pm_dbgg_stat_get(k));
}
