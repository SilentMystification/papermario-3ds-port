# LOG2 host test generator. Reads every pm_log* call with a literal format in 3ds/src and src, and writes logfmt_cases.inc:
# one C function per distinct format, with typed arguments generated at run time by the test's RNG (see logfmt_test.c).
# Run: py -3 3ds/tests/logfmt/gen_logfmt.py  (repo root). Formats that the deferred path refuses (%n, %L, %j, %z, %t, %q, unknown,
# wide %lc %ls) are counted and skipped: they take the vsnprintf fallback, not this test.
import codecs, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SRC_DIRS = [os.path.join(ROOT, "3ds", "src"), os.path.join(ROOT, "src")]
CALL = re.compile(r'\bpm_log(?:_e|_w|_i|_d|_hw|_prof_line)?\s*\(\s*((?:"(?:[^"\\n]|\.)*"\s*)+)')
LIT = re.compile(r'"((?:[^"\\n]|\.)*)"')
POOL = ["", "a", "abc", "hello world", "crash.txt", "0123456789abcdef", "Mario & Luigi", "x" * 40]

def conversions(fmt):
    """Yield (kind, conv, ll, lsingle, is_star_list) per argument in order; None when refused."""
    out = []
    i = 0
    n = len(fmt)
    while i < n:
        if fmt[i] != "%":
            i += 1
            continue
        if i + 1 < n and fmt[i + 1] == "%":
            i += 2
            continue
        j = i + 1
        while j < n and fmt[j] in "-+ #0":
            j += 1
        stars = 0
        if j < n and fmt[j] == "*":
            stars += 1
            j += 1
        else:
            while j < n and fmt[j].isdigit():
                j += 1
        if j < n and fmt[j] == ".":
            j += 1
            if j < n and fmt[j] == "*":
                stars += 1
                j += 1
            else:
                while j < n and fmt[j].isdigit():
                    j += 1
        ll = lsingle = False
        if j < n and fmt[j] == "h":
            j += 1
            if j < n and fmt[j] == "h":
                j += 1
        elif j < n and fmt[j] == "l":
            j += 1
            if j < n and fmt[j] == "l":
                j += 1
                ll = True
            else:
                lsingle = True
        elif j < n and fmt[j] in "Ljztq":
            return None
        if j >= n:
            return None
        cv = fmt[j]
        if cv in "diuoxXpc":
            if cv == "c" and (ll or lsingle):
                return None
            kind = "ll" if ll else "word"
        elif cv in "feEgGaAF":
            if ll:
                return None
            kind = "dbl"
        elif cv == "s":
            if ll or lsingle:
                return None
            kind = "str"
        else:
            return None
        for _ in range(stars):
            out.append(("word", "*", False, False))
        out.append((kind, cv, ll, lsingle))
        if sum(2 if a[0] in ("ll", "dbl") else 1 for a in out) > 16:
            return None  # more than LF_MAX_ARGS words: refused by lf_scan
        i = j + 1
    return out

def arg_expr(kind, cv, ll, lsingle):
    if kind == "word" and cv == "*":
        return "(int)RND_SMALL()"
    if kind == "word":
        if cv == "c":
            return "(int)('a' + rnd() % 26)"
        if cv == "p":
            return "(void*)(uintptr_t)rnd()"
        if cv in "uoxX":
            return "(unsigned long)rnd()" if lsingle else "(unsigned)rnd()"
        return "(long)(int)rnd()" if lsingle else "(int)rnd()"
    if kind == "ll":
        return "(unsigned long long)rnd64()" if cv in "uoxX" else "(long long)rnd64()"
    if kind == "dbl":
        return "(double)((int)rnd() % 200001 - 100000) / 7.0"
    return "pool((int)rnd())"

def main():
    fmts = {}
    skipped = 0
    for d in SRC_DIRS:
        for root, _, files in os.walk(d):
            for fn in files:
                if not fn.endswith((".c", ".h")):
                    continue
                text = open(os.path.join(root, fn), encoding="utf-8", errors="replace").read()
                for m in CALL.finditer(text):
                    lit = "".join(LIT.findall(m.group(1)))
                    try:
                        f = codecs.decode(lit, "unicode_escape")
                    except Exception:
                        continue
                    if f in fmts:
                        continue
                    conv = conversions(f)
                    if conv is None:
                        skipped += 1
                        fmts[f] = None
                    else:
                        fmts[f] = conv
    ok = [(f, c) for f, c in fmts.items() if c is not None]
    lines = ["/* generated by gen_logfmt.py: %d formats, %d refused (fallback) */" % (len(ok), skipped)]
    for idx, (f, conv) in enumerate(ok):
        args = ", ".join(arg_expr(*a[0:1], a[1], a[2], a[3]) if a[0] != "word" or a[1] != "*" else arg_expr("word", "*", False, False) for a in conv)
        cfmt = "\"" + f.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\n").replace("\t", "\t").replace("\x1b", "\x1b") + "\""
        lines.append("static void case_%d(void) { for (int rep = 0; rep < REPS; rep++) check(%d, %s%s); }" % (idx, idx, cfmt, (", " + args) if args else ""))
    lines.append("static void (*const cases[])(void) = {%s};" % ", ".join("case_%d" % i for i in range(len(ok))))
    lines.append("#define NCASES %d" % len(ok))
    out = os.path.join(os.path.dirname(__file__), "logfmt_cases.inc")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("formats %d, refused %d -> %s" % (len(ok), skipped, out))

if __name__ == "__main__":
    sys.exit(main())
